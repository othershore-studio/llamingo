type fakeGen struct {
	calls  int
	prompt string
	opts   imagegen.Options
}

func (f *fakeGen) Generate(ctx context.Context, prompt string, opts imagegen.Options) (imagegen.Image, error) {
	f.calls++
	f.prompt = prompt
	f.opts = opts
	return imagegen.Image{Data: []byte("PNGDATA"), MIME: "image/png", Seed: 4242}, nil
}

type fakeSink struct {
	name string
	data []byte
}

func (s *fakeSink) Save(ctx context.Context, name string, data []byte) (string, error) {
	s.name = name
	s.data = data
	return "attachments/" + name, nil
}

type fixedPrompter struct{ allow bool }

func (p fixedPrompter) Ask(ctx context.Context, req permission.Request, allowed []permission.Scope) (permission.Decision, error) {
	return permission.Decision{Allow: p.allow, Scope: permission.ScopeSession}, nil
}

func gate(allow bool) *permission.Gate {
	return permission.New(fixedPrompter{allow}, permission.NewMemoryGrantStore())
}

func cfg1() imagegen.Config {
	return imagegen.Config{
		Default: "z_image_turbo",
		Models:  []imagegen.ModelConfig{{Name: "z_image_turbo", Modules: []string{"qwen3_4b", "z_image_ae"}}},
	}
}

func TestGenerateImageSavesOutOfBand(t *testing.T) {
	gen := &fakeGen{}
	sink := &fakeSink{}
	tool := imagegen.NewTool(gen, sink, gate(true), cfg1())

	out, err := tool.Call(context.Background(), imagegen.ToolName, `{"prompt":"a red fox","seed":7}`)
	if err != nil {
		t.Fatal(err)
	}
	// The recipe comes from config (z_image → 8 steps, CFG 1, Euler), not the model.
	if gen.calls != 1 || gen.prompt != "a red fox" || gen.opts.Model != "z_image_turbo" ||
		gen.opts.Steps != 8 || gen.opts.CFG != 1 || gen.opts.Sampler != "Euler" || gen.opts.Seed != 7 ||
		len(gen.opts.Modules) != 2 {
		t.Errorf("generator opts = %+v (prompt %q)", gen.opts, gen.prompt)
	}
	if string(sink.data) != "PNGDATA" {
		t.Errorf("sink received %q, want the generated bytes", sink.data)
	}
	// The result is an out-of-band ref the model is told to embed, with the seed.
	if !strings.Contains(out, "![generated image](attachments/") || !strings.Contains(out, "seed 4242") {
		t.Errorf("result = %q", out)
	}
	if !strings.HasSuffix(sink.name, ".png") || sink.name == "generated.png" {
		t.Errorf("saved name = %q, want a unique .png", sink.name)
	}
}

func TestGateDeniedBlocksGeneration(t *testing.T) {
	gen := &fakeGen{}
	tool := imagegen.NewTool(gen, &fakeSink{}, gate(false), cfg1())

	out, err := tool.Call(context.Background(), imagegen.ToolName, `{"prompt":"x"}`)
	if err != nil {
		t.Fatalf("a denial should be a result, not an error: %v", err)
	}
	if gen.calls != 0 {
		t.Errorf("generator ran despite denial (calls = %d)", gen.calls)
	}
	if !strings.Contains(strings.ToLower(out), "not generated") {
		t.Errorf("denial result = %q, want it to say the image was not generated", out)
	}
}

func TestUnknownModelAndListing(t *testing.T) {
	tool := imagegen.NewTool(&fakeGen{}, &fakeSink{}, gate(true), cfg1())

	// An unknown model is reported (as a result), not generated.
	out, _ := tool.Call(context.Background(), imagegen.ToolName, `{"prompt":"x","model":"nope"}`)
	if !strings.Contains(out, "nope") || !strings.Contains(out, "list_image_models") {
		t.Errorf("unknown-model result = %q", out)
	}

	// list_image_models shows the configured model and its prompt style.
	lst, _ := tool.Call(context.Background(), imagegen.ToolListModels, `{}`)
	if !strings.Contains(lst, "z_image_turbo") || !strings.Contains(lst, "natural") {
		t.Errorf("list result = %q", lst)
	}
}

// concurrencyGen records how many generations overlap, to prove serialization.
type concurrencyGen struct {
	active, max, calls int32
}

func (g *concurrencyGen) Generate(ctx context.Context, prompt string, opts imagegen.Options) (imagegen.Image, error) {
	atomic.AddInt32(&g.calls, 1)
	n := atomic.AddInt32(&g.active, 1)
	for { // track the high-water mark of concurrent calls
		m := atomic.LoadInt32(&g.max)
		if n <= m || atomic.CompareAndSwapInt32(&g.max, m, n) {
			break
		}
	}
	time.Sleep(15 * time.Millisecond) // widen the window so an overlap would show
	atomic.AddInt32(&g.active, -1)
	return imagegen.Image{Data: []byte("PNG"), MIME: "image/png", Seed: 1}, nil
}

// nopSink is a stateless AttachmentSink (no fields to race under concurrency).
type nopSink struct{}

func (nopSink) Save(ctx context.Context, name string, data []byte) (string, error) {
	return "attachments/" + name, nil
}

// Image generation is serialized: on a single shared GPU, two requests must never
// run at once (they would contend and can OOM the chat model mid-turn).
func TestGenerationIsSerialized(t *testing.T) {
	gen := &concurrencyGen{}
	tool := imagegen.NewTool(gen, nopSink{}, gate(true), cfg1())

	const n = 5
	var wg sync.WaitGroup
	for i := 0; i < n; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			_, _ = tool.Call(context.Background(), imagegen.ToolName, `{"prompt":"x"}`)
		}()
	}
	wg.Wait()

	if gen.calls != n {
		t.Fatalf("generator ran %d times, want %d", gen.calls, n)
	}
	if gen.max != 1 {
		t.Errorf("max concurrent generations = %d, want 1 (serialized)", gen.max)
	}
}

func TestToolAdvertised(t *testing.T) {
	defs := imagegen.NewTool(&fakeGen{}, &fakeSink{}, gate(true), cfg1()).Tools()
	if len(defs) != 2 {
		t.Fatalf("tool defs = %+v, want 2", defs)
	}
	names := map[string]bool{defs[0].Name: true, defs[1].Name: true}
	if !names[imagegen.ToolName] || !names[imagegen.ToolListModels] {
		t.Errorf("tool names = %v, want generate_image + list_image_models", names)
	}
}

// AutoPickable infers from the name — SDXL/SD1.5 on, modern DiTs off — and an
// explicit AutoPick overrides either way.
func TestAutoPickable(t *testing.T) {
	yes, no := true, false
	cases := []struct {
		m    imagegen.ModelConfig
		want bool
	}{
		{imagegen.ModelConfig{Name: "DreamShaperXL_Turbo_SFW"}, true},
		{imagegen.ModelConfig{Name: "Juggernaut-XI-byRunDiffusion"}, true},
		{imagegen.ModelConfig{Name: "NoobAI-XL-v1.1"}, true},
		{imagegen.ModelConfig{Name: "z_image_turbo"}, false},
		{imagegen.ModelConfig{Name: "flux-2-klein-4b"}, false},
		{imagegen.ModelConfig{Name: "qwen-image"}, false},
		{imagegen.ModelConfig{Name: "flux-2-klein-4b", AutoPick: &yes}, true},
		{imagegen.ModelConfig{Name: "DreamShaperXL_Turbo_SFW", AutoPick: &no}, false},
	}
	for _, c := range cases {
		if got := c.m.AutoPickable(); got != c.want {
			t.Errorf("AutoPickable(%q, override=%v) = %v, want %v", c.m.Name, c.m.AutoPick, got, c.want)
		}
	}
}

// list_image_models shows every configured model but marks the non-auto-pickable
// ones opt-in, so the model is steered to the safe set (the hard stop is in
// generate; see TestGenerateRefusesNonAutoPickModel).
func TestListModelsMarksOptIn(t *testing.T) {
	cfg := imagegen.Config{
		Default: "DreamShaperXL_Turbo_SFW",
		Models: []imagegen.ModelConfig{
			{Name: "DreamShaperXL_Turbo_SFW"},
			{Name: "flux-2-klein-4b"}, // modern DiT → opt-in
		},
	}
	lst, _ := imagegen.NewTool(&fakeGen{}, nopSink{}, gate(true), cfg).Call(context.Background(), imagegen.ToolListModels, `{}`)
	if !strings.Contains(lst, "DreamShaperXL_Turbo_SFW") || !strings.Contains(lst, "flux-2-klein-4b") {
		t.Errorf("list should show both models: %q", lst)
	}
	if !strings.Contains(strings.ToLower(lst), "opt-in") {
		t.Errorf("list should mark the heavy model opt-in: %q", lst)
	}
}

// A model that isn't auto-pickable is refused as a result (not generated), so the
// model can't drive a heavy DiT load on the shared GPU on its own.
func TestGenerateRefusesNonAutoPickModel(t *testing.T) {
	gen := &fakeGen{}
	cfg := imagegen.Config{
		Default: "DreamShaperXL_Turbo_SFW",
		Models: []imagegen.ModelConfig{
			{Name: "DreamShaperXL_Turbo_SFW"},
			{Name: "flux-2-klein-4b"},
		},
	}
	out, err := imagegen.NewTool(gen, nopSink{}, gate(true), cfg).Call(context.Background(), imagegen.ToolName, `{"prompt":"x","model":"flux-2-klein-4b"}`)
	if err != nil {
		t.Fatalf("a refusal should be a result, not an error: %v", err)
	}
	if gen.calls != 0 {
		t.Errorf("a non-auto-pick model should not generate (calls=%d)", gen.calls)
	}
	if !strings.Contains(strings.ToLower(out), "not enabled") {
		t.Errorf("refusal = %q, want a 'not enabled for automatic use' message", out)
	}
}

// With no model named, a generation reuses the last-used model (while it's still
// auto-pickable) instead of the configured default — it's likely resident, so no
// reload. Both models here are SDXL (auto-pickable).
func TestStickyDefaultReusesLastSafeModel(t *testing.T) {
	gen := &fakeGen{}
	cfg := imagegen.Config{
		Default: "DreamShaperXL_Turbo_SFW",
		Models: []imagegen.ModelConfig{
			{Name: "DreamShaperXL_Turbo_SFW"},
			{Name: "Juggernaut-XI-byRunDiffusion"},
		},
	}
	tool := imagegen.NewTool(gen, nopSink{}, gate(true), cfg)
	ctx := context.Background()

	if _, err := tool.Call(ctx, imagegen.ToolName, `{"prompt":"a","model":"Juggernaut-XI-byRunDiffusion"}`); err != nil {
		t.Fatal(err)
	}
	if gen.opts.Model != "Juggernaut-XI-byRunDiffusion" {
		t.Fatalf("explicit model = %q, want Juggernaut", gen.opts.Model)
	}
	if _, err := tool.Call(ctx, imagegen.ToolName, `{"prompt":"b"}`); err != nil {
		t.Fatal(err)
	}
	if gen.opts.Model != "Juggernaut-XI-byRunDiffusion" {
		t.Errorf("sticky default = %q, want the last-used Juggernaut (not the configured default)", gen.opts.Model)
	}
}
