package imagegen_test

import (
	"context"
	"testing"

	"github.com/othershore-studio/llamingo/internal/imagegen"
	"github.com/othershore-studio/llamingo/internal/permission"
)

type fakeGen struct {
	calls  int
	prompt string
	opts   imagegen.Options
}

func (f *fakeGen) Generate(ctx context.Context, prompt string, opts imagegen.Options) (imagegen.Image, error) {
	f.calls++
	f.prompt = prompt
	f.opts = opts
	return imagegen.Image{Data: []byte("PNGDATA"), MIME: "image/png"}, nil
}

type fakeSink struct {
	name string
	data []byte
}

func (s *fakeSink) Save(ctx context.Context, name string, data []byte) (string, error) {
	s.name = name
	s.data = data
	return "attachments/" + name, nil
}

type fixedPrompter struct{ allow bool }

func (p fixedPrompter) Ask(ctx context.Context, req permission.Request, allowed []permission.Scope) (permission.Decision, error) {
	return permission.Decision{Allow: p.allow, Scope: permission.ScopeSession}, nil
}

func gate(allow bool) *permission.Gate {
	return permission.New(fixedPrompter{allow}, permission.NewMemoryGrantStore())
}

func TestGenerateImageSavesOutOfBand(t *testing.T) {
	gen := &fakeGen{}
	sink := &fakeSink{}
	tool := imagegen.NewTool(gen, sink, gate(true))

	out, err := tool.Call(context.Background(), imagegen.ToolName, `{"prompt":"a red fox","width":512,"seed":7}`)
	if err != nil {
		t.Fatal(err)
	}
	if gen.calls != 1 || gen.prompt != "a red fox" || gen.opts.Width != 512 || gen.opts.Seed != 7 {
		t.Errorf("generator got %+v (prompt %q)", gen.opts, gen.prompt)
	}
	if string(sink.data) != "PNGDATA" {
		t.Errorf("sink received %q, want the generated bytes", sink.data)
	}
	if out != "image saved: attachments/generated.png" {
		t.Errorf("result = %q (should be an out-of-band ref, not bytes)", out)
	}
}

func TestGateDeniedBlocksGeneration(t *testing.T) {
	gen := &fakeGen{}
	tool := imagegen.NewTool(gen, &fakeSink{}, gate(false))

	if _, err := tool.Call(context.Background(), imagegen.ToolName, `{"prompt":"x"}`); err == nil {
		t.Fatal("want a refusal when the gate denies")
	}
	if gen.calls != 0 {
		t.Errorf("generator ran despite denial (calls = %d)", gen.calls)
	}
}

func TestToolAdvertised(t *testing.T) {
	defs := imagegen.NewTool(&fakeGen{}, &fakeSink{}, gate(true)).Tools()
	if len(defs) != 1 || defs[0].Name != imagegen.ToolName {
		t.Fatalf("tool defs = %+v, want one %q", defs, imagegen.ToolName)
	}
}
