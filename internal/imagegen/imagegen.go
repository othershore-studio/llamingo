// Package imagegen is the first native (client-executed) tool: image
// generation. A Generator seam sits in front of forge/ComfyUI; the Tool exposes
// it to the model, runs it through the permission gate, and returns an
// out-of-band attachment reference rather than the image bytes — keeping bulk
// data out of the model's context. Prompts pass through verbatim. See
// docs/architecture.md → "Image generation".
package imagegen

import (
	"context"
	"crypto/rand"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"strings"
	"sync"
	"time"

	"github.com/othershore-studio/llamingo/internal/backend"
	"github.com/othershore-studio/llamingo/internal/permission"
)

// Options is the full generation recipe for one image: the prompt's companions
// (negative, seed) plus the per-model settings (checkpoint, steps, CFG, sampler,
// scheduler, modules, resolution). The model never sets the recipe — it is filled
// from the selected model's saved config — so steps/CFG are never guessed.
type Options struct {
	Model              string   // checkpoint name → override_settings.sd_model_checkpoint
	Steps              int      //
	CFG                float64  // → cfg_scale
	Sampler, Scheduler string   // Forge's exact names, e.g. "Euler" / "simple"
	Modules            []string // DiT modules → override_settings.forge_additional_modules
	Width, Height      int      //
	Seed               int      // <= 0 means random
	Negative           string   //
}

// Image is a generated image and the datum worth keeping with it — the seed
// Forge actually used, so the same image can be reproduced.
type Image struct {
	Data []byte
	MIME string // e.g. "image/png"
	Seed int64  // the actual seed (from Forge's info), for reuse
}

// Generator produces an image from a prompt. forge/ComfyUI implementations sit
// behind this seam (parallel to backend.Backend); tests use a fake.
type Generator interface {
	Generate(ctx context.Context, prompt string, opts Options) (Image, error)
}

// AttachmentSink saves generated bytes out-of-band and returns a reference
// (e.g. a path under the conversation's attachments/). The store implements it;
// tests fake it.
type AttachmentSink interface {
	Save(ctx context.Context, name string, data []byte) (ref string, err error)
}

// ToolName generates an image; ToolListModels lists the configured models.
const (
	ToolName       = "generate_image"
	ToolListModels = "list_image_models"
)

// genSem serializes image generation to one at a time across the whole app. On a
// single shared GPU, concurrent generations only contend — and a heavy model load
// can OOM the chat model mid-turn — so a second request waits its turn rather than
// racing. There is no setting: running two at once on one GPU never wins; a bigger
// card or a second backend is a future concern (Taita's, eventually).
var genSem = make(chan struct{}, 1)

// lastModel remembers the checkpoint the last successful generation used, which
// ≈ what Forge has resident. A generation that names no model prefers this (when
// it's still auto-pickable) over the configured default, to skip the few-second
// checkpoint reload. Guarded because the permission gate runs before the queue.
var (
	lastModelMu sync.Mutex
	lastModelNm string
)

func lastModel() string {
	lastModelMu.Lock()
	defer lastModelMu.Unlock()
	return lastModelNm
}

func setLastModel(name string) {
	lastModelMu.Lock()
	lastModelNm = name
	lastModelMu.Unlock()
}

// Tool is the built-in image-generation tool. Its Tools/Call methods satisfy the
// MCP loop's Registry, so it is offered alongside MCP tools. It is wired only
// when a Forge URL and at least one model are configured.
type Tool struct {
	gen  Generator
	sink AttachmentSink
	gate *permission.Gate
	cfg  Config
}

// NewTool returns the image-generation tool for the given configured models.
func NewTool(gen Generator, sink AttachmentSink, gate *permission.Gate, cfg Config) *Tool {
	return &Tool{gen: gen, sink: sink, gate: gate, cfg: cfg}
}

// Tools advertises the image tools. The model supplies only the prompt, an
// optional negative prompt, an optional seed (to reproduce), and an optional
// model name — never the sampling recipe, which comes from the model's config.
func (t *Tool) Tools() []backend.ToolDef {
	return []backend.ToolDef{
		{
			Name: ToolName,
			Description: "Generate an image from a text prompt — this is the ONLY way to show an image. Give the prompt, and optionally a " +
				"negative prompt, a seed, or a model name; sampling comes from config. The image is shown to the user automatically: never " +
				"write a markdown image link or an attachments/ path yourself, and never invent a file name.",
			Parameters: json.RawMessage(`{"type":"object","properties":{` +
				`"prompt":{"type":"string","description":"what to draw; match the model's prompt style"},` +
				`"negative_prompt":{"type":"string","description":"what to avoid (ignored by CFG-1 models)"},` +
				`"seed":{"type":"integer","description":"reuse a seed to reproduce an image; omit for a new random one"},` +
				`"model":{"type":"string","description":"which configured model to use; omit for the default"}},"required":["prompt"]}`),
		},
		{
			Name:        ToolListModels,
			Description: "List the configured image-generation models and how to prompt each (natural language, booru tags, or phrases).",
			Parameters:  json.RawMessage(`{"type":"object","properties":{}}`),
		},
	}
}

// Call dispatches an image tool by name.
func (t *Tool) Call(ctx context.Context, name, arguments string) (string, error) {
	switch name {
	case ToolName:
		return t.generate(ctx, arguments)
	case ToolListModels:
		return t.listModels(), nil
	default:
		return "", fmt.Errorf("imagegen: unknown tool %q", name)
	}
}

// generate resolves the model's recipe, gates on the prompt, runs the generator,
// saves the image out-of-band, and tells the model how to show it (with the seed
// for reuse). A denial or a missing model is returned as a result, not an error.
func (t *Tool) generate(ctx context.Context, arguments string) (string, error) {
	var a struct {
		Prompt   string `json:"prompt"`
		Negative string `json:"negative_prompt"`
		Seed     int    `json:"seed"`
		Model    string `json:"model"`
	}
	if err := json.Unmarshal([]byte(arguments), &a); err != nil {
		return "", fmt.Errorf("imagegen: arguments: %w", err)
	}
	if strings.TrimSpace(a.Prompt) == "" {
		return "", fmt.Errorf("imagegen: prompt is required")
	}
	mc, result, ok := t.resolveModel(a.Model)
	if !ok {
		return result, nil // a result explaining why (unknown / not auto-pickable / none configured)
	}
	r := mc.Recipe()

	allow, err := t.gate.Allow(ctx, permission.Request{
		ToolID: "native:" + ToolName,
		Label:  "generate an image",
		Detail: fmt.Sprintf("%s\n(model: %s)", a.Prompt, mc.Name),
		Risk:   permission.RiskLow,
	})
	if err != nil {
		return "", err
	}
	if !allow {
		return "Not generated: the user declined the approval prompt for this image. Tell them it was not created because they declined, and that they can ask again to retry. Do not claim an image was made, and do not say you cannot generate images — you can; they simply declined this one.", nil
	}

	// Wait our turn: one generation at a time on the shared GPU (see genSem).
	// Acquired after the gate, so the consent prompt never waits behind the queue;
	// ctx-aware, so an aborted turn doesn't hold the line.
	select {
	case genSem <- struct{}{}:
	case <-ctx.Done():
		return "Image generation was canceled before it started.", nil
	}
	start := time.Now()
	img, err := t.gen.Generate(ctx, a.Prompt, Options{
		Model: mc.Name, Modules: mc.Modules,
		Steps: r.Steps, CFG: r.CFG, Sampler: r.Sampler, Scheduler: r.Scheduler,
		Width: r.Width, Height: r.Height, Seed: a.Seed, Negative: a.Negative,
	})
	<-genSem // release the queue; saving/encoding below is not GPU-bound
	if err != nil {
		return "Image generation failed: " + err.Error(), nil
	}
	setLastModel(mc.Name) // now resident in Forge — prefer it next time, to skip a reload
	fname, err := randomName(extForMIME(img.MIME))
	if err != nil {
		return "", err
	}
	ref, err := t.sink.Save(ctx, fname, img.Data)
	if err != nil {
		return "", err
	}
	return fmt.Sprintf("Image generated with %s (seed %d, %s): ![generated image](%s)",
		mc.Name, img.Seed, time.Since(start).Round(time.Second), ref), nil
}

// resolveModel picks the model for a generation. A named model must be configured
// and auto-pickable (heavy DiTs are opt-in — see ModelConfig.AutoPickable); an
// unnamed one prefers the last-used model when it's still auto-pickable (likely
// resident in Forge, so no reload), else the configured default. ok is false when
// nothing usable resolves, and result is the message to show in that case.
func (t *Tool) resolveModel(name string) (mc ModelConfig, result string, ok bool) {
	if name != "" {
		m, found := t.cfg.Model(name)
		if !found {
			return ModelConfig{}, fmt.Sprintf("No image model named %q. Call list_image_models to see the ones available.", name), false
		}
		if !m.AutoPickable() {
			return ModelConfig{}, fmt.Sprintf("The %q model is not enabled for automatic use — it may need more VRAM than the shared GPU can spare. The user can enable it in the image config.", name), false
		}
		return m, "", true
	}
	if last := lastModel(); last != "" {
		if m, found := t.cfg.Model(last); found && m.AutoPickable() {
			return m, "", true
		}
	}
	m, found := t.cfg.Model("")
	if !found {
		return ModelConfig{}, "No default image model is configured. Call list_image_models, or ask the user to set one.", false
	}
	return m, "", true
}

// listModels reports the configured models and their prompt style, so the model
// can pick one and prompt it correctly.
func (t *Tool) listModels() string {
	if len(t.cfg.Models) == 0 {
		return "No image-generation models are configured."
	}
	var b strings.Builder
	b.WriteString("Configured image models")
	if t.cfg.Default != "" {
		fmt.Fprintf(&b, " (default: %s)", t.cfg.Default)
	}
	b.WriteString(":\n")
	for _, m := range t.cfg.Models {
		r := m.Recipe()
		fmt.Fprintf(&b, "- %s — prompt style: %s", m.Name, r.PromptStyle)
		if r.Note != "" {
			fmt.Fprintf(&b, " (%s)", r.Note)
		}
		if !m.AutoPickable() {
			b.WriteString(" — opt-in only; the user must enable it (heavy on a shared GPU)")
		}
		b.WriteByte('\n')
	}
	return b.String()
}

func randomName(ext string) (string, error) {
	var b [8]byte
	if _, err := rand.Read(b[:]); err != nil {
		return "", fmt.Errorf("imagegen: generate name: %w", err)
	}
	return hex.EncodeToString(b[:]) + ext, nil
}

func extForMIME(mime string) string {
	switch mime {
	case "image/png":
		return ".png"
	case "image/jpeg":
		return ".jpg"
	case "image/webp":
		return ".webp"
	default:
		return ".bin"
	}
}
